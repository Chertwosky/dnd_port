function titleCaseSpell(name) {
  return String(name || "")
    .trim()
    .split(/\s+/)
    .map((w) => (w ? w[0].toUpperCase() + w.slice(1).toLowerCase() : w))
    .join(" ")
    .replace(/\bOf\b/g, "of")
    .replace(/\bAnd\b/g, "and")
    .replace(/\bThe\b/g, "the")
    .replace(/\bFrom\b/g, "from");
}

export function cleanMarkdown(text) {
  let t = String(text || "");
  t = t.replace(/\r\n/g, "\n");
  t = t.replace(/^\|?\s*-{3,}\s*\|.*$/gm, "");
  t = t.replace(/^\|\s*([^|\n]+)\s*\|\s*([^|\n]+)\s*\|?\s*$/gm, (_, a, b) => {
    const left = String(a).trim();
    const right = String(b)
      .split(",")
      .map((s) => {
        const raw = s.trim();
        const titled = titleCaseSpell(raw);
        const ru = spellNameRu(titled);
        return ru !== titled ? ru : spellNameRu(raw) !== raw ? spellNameRu(raw) : raw;
      })
      .join(", ");
    if (/^(paladin|cleric|druid|level|уровень)/i.test(left) && /spell/i.test(right)) return "";
    return `${left}: ${right}`;
  });
  t = t.replace(/^#{1,6}\s*/gm, "");
  t = t.replace(/\*\*([^*]+)\*\*/g, "$1");
  t = t.replace(/\*([^*]+)\*/g, "$1");
  t = t.replace(/_([^_]+)_/g, "$1");
  t = t.replace(/\n{3,}/g, "\n\n");
  return t.trim();
}

function applyPhrases(text) {
  let out = String(text || "");
  for (const [en, ru] of PHRASES) {
    out = out.split(en).join(ru);
  }
  return out;
}

