function applyPhrases(text) {
  let out = String(text || "");
  // Сначала длинные фразы (массив уже примерно от длинных к коротким в начале)
  const sorted = [...PHRASES].sort((a, b) => b[0].length - a[0].length);
  for (const [en, ru] of sorted) {
    out = out.split(en).join(ru);
  }
  return out;
}

export function spellNameRu(nameEn) {
  const key = String(nameEn || "").trim();
  if (!key) return key;
  if (SPELL_NAME_RU[key]) return SPELL_NAME_RU[key];
  const titled = key.toLowerCase().replace(/\b([a-z])/g, (ch) => ch.toUpperCase());
  if (SPELL_NAME_RU[titled]) return SPELL_NAME_RU[titled];
  const hit = Object.keys(SPELL_NAME_RU).find((k) => k.toLowerCase() === key.toLowerCase());
  return hit ? SPELL_NAME_RU[hit] : key;
}

