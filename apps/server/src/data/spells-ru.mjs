export function describeSpellRu(spell) {
  const nameEn = String(spell.nameEn || spell.name || "").trim();
  const summary =
    SPELL_SUMMARY_RU[nameEn] ||
    SPELL_SUMMARY_RU[nameEn.toLowerCase().replace(/\b([a-z])/g, (ch) => ch.toUpperCase())] ||
    Object.entries(SPELL_SUMMARY_RU).find(([k]) => k.toLowerCase() === nameEn.toLowerCase())?.[1];
  const raw = String(spell.description || "").trim();
  const translated = applyPhrases(raw)
    .replace(/\n+/g, " ")
    .replace(/\s+/g, " ")
    .trim();
  const higherRaw = spell.higherLevel ? applyPhrases(spell.higherLevel).trim() : "";
  const translatedOk = Boolean(translated) && !looksMostlyEnglish(translated);
  const higherOk = Boolean(higherRaw) && !looksMostlyEnglish(higherRaw);

  // Кураторский русский — главный источник (фразовый патч EN→RU ненадёжен)
  const descriptionRu =
    summary ||
    (translatedOk ? translated : "") ||
    "Описание на русском пока недоступно.";
  const summaryRu =
    summary ||
    (translatedOk ? translated.slice(0, 180) + (translated.length > 180 ? "…" : "") : "") ||
    descriptionRu;

  return {
    summaryRu,
    descriptionRu,
    higherLevelRu: higherOk ? higherRaw : ""
  };
}

function looksMostlyEnglish(text) {
  const t = String(text || "");
  if (!t) return false;
  const latin = (t.match(/[A-Za-z]/g) || []).length;
  const cyr = (t.match(/[А-Яа-яЁё]/g) || []).length;
  if (latin === 0) return false;
  if (cyr === 0 && latin > 8) return true;
  // смешанный текст: если латиницы заметно больше кириллицы — считаем EN
  if (latin > cyr * 0.55) return true;
  return /\b(the|you|your|creature|damage|spell|attack|until|within|radiant|fiend|undead|willing|bonus action)\b/i.test(
    t
  );
}
